-- 악보함에 PDF 말고도 모든 파일(음원, 문서 등)을 올릴 수 있게 한다.
-- 사진은 앱에서 PDF 악보로 합쳐 올리므로 확대와 필기를 그대로 쓸 수 있다.
-- 파일 하나의 크기 한도는 Supabase 무료 플랜의 파일 한도(50MB)에 맞춘다.
-- 이미 설치된 사이트에서도 자동으로 적용되므로 여러 번 실행해도 결과가 같게 쓴다.
------------------------------------------------------------
update storage.buckets
set allowed_mime_types = null, file_size_limit = 52428800
where id = 'sheets';
